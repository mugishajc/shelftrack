CREATE TABLE books (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn             VARCHAR(13)  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    author           VARCHAR(255) NOT NULL,
    published_year   INTEGER,
    total_copies     INTEGER      NOT NULL,
    available_copies INTEGER      NOT NULL,
    version          BIGINT       NOT NULL DEFAULT 0,
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT uk_books_isbn UNIQUE (isbn),
    CONSTRAINT ck_books_copies CHECK (available_copies >= 0 AND available_copies <= total_copies)
);

CREATE TABLE members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(120) NOT NULL,
    email      VARCHAR(254) NOT NULL,
    phone      VARCHAR(20),
    status     VARCHAR(20)  NOT NULL,
    joined_on  DATE         NOT NULL,
    CONSTRAINT uk_members_email UNIQUE (email)
);

CREATE TABLE loans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id      BIGINT        NOT NULL REFERENCES books (id),
    member_id    BIGINT        NOT NULL REFERENCES members (id),
    borrowed_on  DATE          NOT NULL,
    due_on       DATE          NOT NULL,
    returned_on  DATE,
    renewals     INTEGER       NOT NULL DEFAULT 0,
    fine_amount  DECIMAL(10, 2) NOT NULL DEFAULT 0,
    version      BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX ix_loans_member_open ON loans (member_id, returned_on);
CREATE INDEX ix_loans_due_open ON loans (due_on, returned_on);
CREATE INDEX ix_books_title ON books (title);
